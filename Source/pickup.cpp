/* Each lookup returns the record of its pickup definition table whose id matches, or null when none does. */
static inline PowerupIdEntry *find_handler(char *table, s32 count, s32 size, s32 id) {
    PowerupIdEntry *entry;
    s32 i;
    entry = (PowerupIdEntry *)table;
    i = count;
    do {
        if (entry->id == id) {
            return entry;
        }
        i--;
        entry = (PowerupIdEntry *)((char *)entry + size);
    } while (i != -1);
    return 0;
}

/* Returns whether a player actor can use the pickup: never for non-players or disabled actors; always during a
   team round when the model says so; otherwise by the pickup's definition table. A power-up is usable when the
   actor's team matches a special model id, or its slot is free while the two states 3 and 7 are not both in use.
   A weapon is usable on those teams or while below the ammo capacity level. A health item is usable while the
   actor's health is below its maximum. Any ammo item is usable. A special item is usable unless it is item 0xBD6. */
s32 Pickup_CanCollect(s32 prop, Player *actor) {
    PickupPowerupDefinition *powerup;
    PickupWeaponDefinition *weapon;
    PickupHealthDefinition *item;
    Shared_PickupAmmoDefinition *bonus;
    PickupSpecialDefinition *special;
    s32 id;
    s32 level;
    s32 noState3;
    s32 noState7;
    s32 i;
    Player *player;
    id = InstHdr_GetActorType(prop);
    if (((actor)->kind == 1 && ((actor)->weaponFlags & 0x300000) != 0)) {
        player = actor;
        if (player->health == 0) {
            return 0;
        }
        if (g_gameSettings.counters.m_bFragTagOn != 0 && player->profile->bonus != 0) {
            return 1;
        }
        powerup = (PickupPowerupDefinition *)find_handler((char *)g_pickupPowerupDefinitions, 3, 24, id);
        if (powerup != 0) {
            noState3 = 1;
            noState7 = 1;
            if (player->objectId == g_playerSpecialModelIds[0] || player->objectId == g_playerSpecialModelIds[1]) {
                return 1;
            }
            if (player->weaponSlots[powerup->ids.slot].action != -1) {
                return 0;
            }
            for (i = 0; i < 22; i++) {
                if (player->weaponSlots[i].action == 3) {
                    noState3 = 0;
                } else if (player->weaponSlots[i].action == 7) {
                    noState7 = 0;
                }
            }
            if (noState3 || noState7) {
                return 1;
            }
            return 0;
        }
        weapon = (PickupWeaponDefinition *)find_handler((char *)g_pickupWeaponDefinitions, 5, 20, id);
        if (weapon != 0) {
            level = Player_GetAmmoCapacity(player, weapon->ids.slot, 0);
            if (player->objectId == g_playerSpecialModelIds[0] || player->objectId == g_playerSpecialModelIds[1]) {
                return 1;
            }
            return player->ammo[weapon->ids.slot] < level;
        }
        item = (PickupHealthDefinition *)find_handler((char *)g_pickupHealthDefinitions, 7, 24, id);
        if (item != 0) {
            return player->health < Player_GetMaxHealth(player);
        }
        bonus = (Shared_PickupAmmoDefinition *)find_handler((char *)g_pickupAmmoDefinitions, 15, 24, id);
        if (bonus != 0) {
            return 1;
        }
        special = (PickupSpecialDefinition *)find_handler((char *)g_pickupSpecialDefinitions, 2, 16, id);
        if (special != 0) {
            if ((player->objectId == g_playerSpecialModelIds[0] || player->objectId == g_playerSpecialModelIds[1]) && special->ids.id != 3030) {
                return 1;
            }
            return special->ids.id != 3030;
        }
        return 0;
    }
    return ((actor)->kind == 1 && ((actor)->weaponFlags & 0x300000) != 0);
}
/* Dispatches an item effect with the given id to an actor that can receive it: looks the id up in each item handler table in turn (g_pickupPowerupDefinitions, g_pickupWeaponDefinitions, g_pickupHealthDefinitions, g_pickupSingleDefinitions, g_pickupAmmoDefinitions, g_pickupTargetedDefinitions and g_pickupSpecialDefinitions) and returns the first nonzero handler result, clearing the given target from every actor's two lock-on slots after the g_pickupAmmoDefinitions handler. */

s32 Pickup_DispatchHandler(Player *actor, s32 target, s32 id) {
    PowerupIdEntry *entry;
    Player *other;
    s32 result;
    result = 0;
    if (actor->health != 0) {
        entry = find_handler(&g_pickupPowerupDefinitions, 3, 24, id);
        if (entry != 0) {
            result = ((PickupDefinition24 *)entry)->apply(actor, (PickupDefinition24 *)entry);
        }
        if (result != 0) {
            return result;
        }
        entry = find_handler(&g_pickupWeaponDefinitions, 5, 20, id);
        if (entry != 0) {
            result = ((AmmoPickupDefinition *)entry)->apply(actor, (AmmoPickupDefinition *)entry);
        }
        if (result != 0) {
            return result;
        }
        entry = find_handler(&g_pickupHealthDefinitions, 7, 24, id);
        if (entry != 0) {
            result = ((HealthPickupDefinition *)entry)->apply(actor, (HealthPickupDefinition *)entry);
        }
        if (result != 0) {
            return result;
        }
        entry = find_handler(&g_pickupSingleDefinitions, 1, 20, id);
        if (entry != 0) {
            result = ((AmmoPickupDefinition *)entry)->apply(actor, (AmmoPickupDefinition *)entry);
        }
        if (result != 0) {
            return result;
        }
        entry = find_handler((char *)g_pickupAmmoDefinitions, 15, 24, id);
        if (entry != 0) {
            result = ((AmmoBundleDefinition *)entry)->apply(actor, (AmmoBundleDefinition *)entry);
        }
        for (other = g_transientPlayerList.actorList; other != 0; other = other->next) {
            if (other->projectiles[0] == (void *)target) {
                other->projectiles[0] = 0;
            } else if (other->projectiles[1] == (void *)target) {
                other->projectiles[1] = 0;
            }
        }
        if (result != 0) {
            return result;
        }
        entry = find_handler(&g_pickupTargetedDefinitions, 15, 16, id);
        if (entry != 0) {
            result = ((TargetedPickupDefinition *)entry)->apply(actor, (TargetedPickupDefinition *)entry, target);
        }
        if (result != 0) {
            return result;
        }
        entry = find_handler(&g_pickupSpecialDefinitions, 2, 16, id);
        if (entry != 0) {
            result = ((PickupCallbackDefinition *)entry)->apply(actor, (PickupCallbackDefinition *)entry);
        }
    }
    return result;
}


s32 Pickup_ApplyWeaponPickup(Player *player, MultiChannelItemEffect *pickup)
{
    s32 changed = 0;
    s32 owned;
    WeaponInfo *weapon;
    u8 **label;
    s32 sound, event;
    if (pickup->effect.argument != -1 && player->weaponSlots[pickup->effect.index].owned) {
        changed = Player_AddAmmo(player, pickup->effect.argument, pickup->third);
        if (!changed) {
            Shared_Game *game = &g_gameSettings;
            if (!(game->local && player->profile->bonus && game->fragTagEnabled)) return 0;
        }
    }
    if (g_frontendScreenStatus.settings.local) { if (!(((WeaponInfo *)g_weaponInfoByType[pickup->effect.index])->flags & 8)) return 0; }
    else if (((WeaponInfo *)g_weaponInfoByType[pickup->effect.index])->flags & 8) return 0;
    owned = player->weaponSlots[pickup->effect.index].owned;
    player->weaponSlots[pickup->effect.index].owned = 1;
    weapon = g_weaponInfoByType[pickup->effect.index];
    if (player->selectedAction < pickup->effect.index) {
        if (player->movementFlags & 0x1000 ? weapon->flags & 2 : weapon->flags & 1) {
            if (!g_frontendScreenStatus.settings.local && !owned) player->weapon = pickup->effect.index;
        }
    }
    label = pickup->effect.resource; sound = pickup->effect.sound; event = pickup->effect.callback;
    if (player->camera) {
        Gsky_StartFade(player->camera, 128, 50, 50, 75, 0, 0, 2);
        if (label != 0) Camera_PostScreenMessage(&g_frontendScreenStatus, player->camera, label[MENU_LANGUAGE]);
    }
    if (sound) SoundElement_PlaySoundAtPosition(sound, player->pos, 0, -1);
    if (event) SoundElement_PlayDialogGroup(event);
    if (!changed) Player_AddAmmo(player, pickup->effect.argument, pickup->third);
    return 1;
}



