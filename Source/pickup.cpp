/* Lets the actor collect the pickup. A recycled pickup (flag 8) can be collected while its state flag 1 is
   set; any other pickup only while it is not yet collected (flag 1 clear). A pickup the handler accepts is
   marked collected, then either recycled or recorded in the level and linked to its source objects. */
void Pickup_TryCollectActor(void *actor, void *pickup) {
    u16 collectedFlags;

    if (((struct Shared_ProjectileView *)pickup)->flags & 8) {
        if (!(((struct Shared_ProjectileView *)pickup)->stateFlags & 1)) {
            return;
        }
    } else if (((struct Shared_ProjectileView *)pickup)->flags & 1) {
        return;
    }
    if (Pickup_DispatchHandler(actor, pickup, InstHdr_GetActorType(pickup)) == 0) {
        return;
    }
    collectedFlags = ((struct Shared_ProjectileView *)pickup)->flags | 1;
    ((struct Shared_ProjectileView *)pickup)->flags = collectedFlags;
    if (collectedFlags & 8) {
        SetN64_RecycleGlobalEffectNode(pickup);
        return;
    }
    Scene_SetLevelRecordStateBit(&g_world, pickup, 1);
    Link_DispatchObjectLinks(((struct Shared_ProjectileView *)pickup)->source, 0x400, actor);
}


